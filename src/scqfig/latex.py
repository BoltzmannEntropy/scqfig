"""Generate latex/scqfig.sty from themes.py, so a document uses the same palette as its figures.

    python -m scqfig.latex            # rewrites latex/scqfig.sty in a source checkout
    python -m scqfig.latex out.sty    # writes elsewhere

The package defines every palette colour (scqBlue, ...), every role of both styles (scqFieldAccent,
scqFolioAccent, ...) and the active style's roles under plain names (scqAccent, scqQubitA, scqLevel0,
scqTileCapacitive, scqChipFlux, ...). It adds \\scqgraphics, which picks the figure of the active
style, pgfplots styles that match the matplotlib ones, and TikZ tiles for circuit elements."""
import pathlib
import sys

from matplotlib.colors import to_hex

from . import __version__
from .themes import PALETTE, THEMES

ROLES = ("ink", "data", "model", "sim", "reference", "assumed", "accent", "signal", "bus", "wash", "light", "tint",
         "overlay")


def cname(key):
    """LaTeX colour name of a palette key: "blue" -> scqBlue."""
    return "scq" + key.capitalize()


def _hex(c):
    return to_hex(c)[1:].upper()


def _camel(s):
    return "".join(w.capitalize() for w in s.split("_"))


def _style_colours(t):
    pre = "scq" + t.name.capitalize()
    out = [(pre + _camel(r), getattr(t, r)) for r in ROLES]
    out += [(f"{pre}Qubit{chr(65 + i)}", c) for i, c in enumerate(t.qubits)]
    out += [(f"{pre}Level{i}", c) for i, c in enumerate(t.levels)]
    out += [(f"{pre}Series{chr(65 + i)}", c) for i, c in enumerate(t.cycle)]
    out += [(f"{pre}Tile{_camel(k)}", c) for k, c in t.tiles.items()]
    out += [(f"{pre}Chip{_camel(k)}", c) for k, c in t.chip.items()]
    return out


def _pgf_dash(d):
    if d == "-":
        return "solid"
    if d == "--":
        return "dashed"
    if d == "-.":
        return "dash dot"
    if d == ":":
        return "dotted"
    on_off = d[1]
    return "dash pattern=" + " ".join(f"{'on' if i % 2 == 0 else 'off'} {v}pt" for i, v in enumerate(on_off))


_PGF_MARK = {"o": "*", "s": "square*", "D": "diamond*", "^": "triangle*", "v": "triangle*"}


def _pgf_style(t):
    """pgfplots axis style and cycle list of theme t."""
    name = t.name
    pre = "scq" + name.capitalize()
    fill = (lambda c: f"fill={c}") if t.data_filled else (lambda c: "fill=white")
    entries = []
    for i in range(len(t.cycle)):
        c = f"{pre}Series{chr(65 + i)}"
        m = _PGF_MARK[t.markers[i]]
        rot = ",rotate=180" if t.markers[i] == "v" else ""
        entries.append(f"{{{c},{_pgf_dash(t.dashes[i])},mark={m},mark options={{solid,{fill(c)}{rot}}}}}")
    font = r"\sffamily" if t.family == "sans-serif" else r"\rmfamily"
    frame = "axis lines=box," if t.box else "axis lines*=left,axis line style={-},"
    ticks = "tick align=inside," if t.ticks == "in" else "tick align=outside,"
    mirror = "xtick pos=both,ytick pos=both," if t.box else "xtick pos=left,ytick pos=left,"
    return [
        rf"  \pgfplotscreateplotcyclelist{{scqfig {name}}}{{%",
        "    " + ",%\n    ".join(entries) + "}",
        rf"  \pgfplotsset{{scqfig {name}/.style={{{frame}{ticks}{mirror}",
        rf"    axis line style={{line width={t.axes_lw}pt,draw={pre}Ink}},",
        rf"    every tick/.style={{line width={t.axes_lw * 0.85:.2f}pt,{pre}Ink}},",
        r"    major tick length=3.2pt,minor tick length=1.8pt,",
        rf"    tick label style={{font={font}\footnotesize}},label style={{font={font}\small}},",
        rf"    legend style={{font={font}\footnotesize,draw={'scqFieldInk' if t.box else 'none'},fill=white}},",
        rf"    every axis plot/.append style={{line width={t.lw}pt,mark size=1.6pt}},",
        rf"    cycle list name=scqfig {name},",
        rf"    colormap={{scqfig {name}}}{{{' '.join(f'rgb255({int(p * 1000)})=({_rgb255(c)})' for p, c in t.cmap_stops)}}}}},",
        rf"    scqfig {name} data/.style={{only marks,mark=*,{pre}Data,mark options={{solid,{fill(pre + 'Data')}}}}},",
        rf"    scqfig {name} model/.style={{no marks,solid,{pre}Model,line width={t.lw}pt}},",
        rf"    scqfig {name} ref/.style={{no marks,{pre}Reference,dash pattern=on 4pt off 2pt,line width=0.7pt}},",
        r"  }",
    ]


def _rgb255(c):
    h = to_hex(c)
    return ",".join(str(int(h[i:i + 2], 16)) for i in (1, 3, 5))


def sty_text():
    """The full text of scqfig.sty."""
    L = [
        "% scqfig.sty -- generated by `python -m scqfig.latex` from src/scqfig/themes.py; do not edit by hand.",
        "% Colours, figure selection and pgfplots/TikZ styles matching the scqfig matplotlib styles.",
        r"%   \usepackage[field]{scqfig}   or   \usepackage[folio,figdir=figures]{scqfig}",
        r"\NeedsTeXFormat{LaTeX2e}",
        rf"\ProvidesPackage{{scqfig}}[2026/10/23 v{__version__} figure styles for superconducting-chip papers]",
        r"\RequirePackage{xcolor}",
        r"\RequirePackage{graphicx}",
        r"\RequirePackage{kvoptions}",
        r"\SetupKeyvalOptions{family=scq,prefix=scq@}",
        r"\def\scq@style{field}\def\scq@Style{Field}",
        r"\DeclareVoidOption{field}{\def\scq@style{field}\def\scq@Style{Field}}",
        r"\DeclareVoidOption{folio}{\def\scq@style{folio}\def\scq@Style{Folio}}",
        r"\DeclareStringOption[figures]{figdir}",
        r"\ProcessKeyvalOptions*",
        "",
        "% ---- palette: four hues, their tints, and greys",
    ]
    L += [rf"\definecolor{{{cname(k)}}}{{HTML}}{{{v[1:].upper()}}}" for k, v in PALETTE.items()]
    names = []
    for t in THEMES.values():
        L += ["", f"% ---- roles of the {t.name} style"]
        cols = _style_colours(t)
        L += [rf"\definecolor{{{n}}}{{HTML}}{{{_hex(c)}}}" for n, c in cols]
        names = [n[len("scq" + t.name.capitalize()):] for n, _ in cols]
    L += ["", "% ---- the active style's roles under plain names (scqAccent, scqQubitA, scqTileCapacitive, ...)"]
    L += [rf"\colorlet{{scq{n}}}{{scq\scq@Style {n}}}" for n in names]
    L += ["",
          "% ---- the figure of the active style: \\scqgraphics[width=\\columnwidth]{t1_decay} loads",
          "%      <figdir>/<style>/t1_decay, so one package option switches every figure",
          r"\newcommand{\scqstyle}{\scq@style}",
          r"\newcommand{\scqgraphics}[2][]{\includegraphics[#1]{\scq@figdir/\scq@style/#2}}",
          "",
          "% ---- pgfplots: axis styles `scqfig field`, `scqfig folio` and `scqfig` (the active one),",
          "%      plot styles `scqfig data`, `scqfig model`, `scqfig ref`",
          r"\AtBeginDocument{\@ifpackageloaded{pgfplots}{%"]
    for t in THEMES.values():
        L += _pgf_style(t)
    L += [r"  \pgfplotsset{scqfig/.style={scqfig \scq@style},",
          r"    scqfig data/.style={scqfig \scq@style\space data},",
          r"    scqfig model/.style={scqfig \scq@style\space model},",
          r"    scqfig ref/.style={scqfig \scq@style\space ref}}%",
          r"}{}%",
          r"\@ifpackageloaded{tikz}{%",
          r"  \tikzset{scq tile/.style={rounded corners=2pt,inner sep=3pt,scq tile fill/#1},",
          r"    scq tile/.default=capacitive,"]
    kinds = list(next(iter(THEMES.values())).tiles)
    L += [rf"    scq tile fill/{k}/.style={{fill=scqTile{_camel(k)}}}" + ("," if i < len(kinds) - 1 else "}%")
          for i, k in enumerate(kinds)]
    L += [r"}{}}",
          "",
          r"\endinput"]
    return "\n".join(L) + "\n"


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    out = pathlib.Path(argv[0]) if argv else pathlib.Path(__file__).resolve().parents[2] / "latex" / "scqfig.sty"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(sty_text())
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
